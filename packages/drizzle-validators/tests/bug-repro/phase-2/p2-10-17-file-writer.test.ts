import { expect, test } from "./_helpers";
import { writeGeneratedFiles } from "../../../src/file-writer";
import type {
	GeneratedData,
	ResolvedPaths,
	TableCodeData,
} from "../../../src/types";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import {
	readFile,
	writeFile,
} from "node:fs/promises";

// P2-10: when a table was removed from the schema source, its stale
// `<table>.ts` output file survived in the output dir forever (the barrel
// no longer re-exported it, but the dead file kept shipping). The writer
// now reconciles stale per-table files after each generation.

// P2-17: `outputPath: node_modules/.drizzle-validators/inner` made the
// writer rm() the internal directory CONCURRENTLY with writing children
// into it — hard ENOENT failure, deterministic. The rm of the internal
// output dir is now sequenced before the writes and skipped entirely when
// the output lives inside it.

function tmpRoot(name: string): string {
	const dir = join(
		process.cwd(),
		"node_modules",
		`.tmp-p2-fw-${name}-${process.pid}`,
	);
	mkdirSync(dir, { recursive: true });
	return dir;
}

const tableData = (
	insertCode: string,
	selectCode: string,
	updateCode: string,
) => ({
	code: "// table",
	exportNames: ["usersInsertSchema", "usersSelectSchema", "usersUpdateSchema"],
	codes: [insertCode, selectCode, updateCode] as TableCodeData["codes"],
});

const data: GeneratedData = {
	code: "export const users = 1;",
	singleFileCode: "export const users = 1;",
	exportNames: ["usersSelectSchema"],
	depPaths: [],
	tableCodes: new Map([["users", tableData("/*ins*/", "/*sel*/", "/*upd*/")]]),
	target: "zod",
	importStatement: "import * as z from 'zod'",
};

const paths = (viteRoot: string, outputPath: string): ResolvedPaths => ({
	absoluteOutputPath: join(viteRoot, outputPath, "index.ts"),
	absoluteOutputDir: join(viteRoot, outputPath),
	dtsPath: join(viteRoot, "typesGenerated.ts"),
	absoluteSchemaPath: join(viteRoot, "schema.ts"),
	tmpDir: join(viteRoot, "node_modules", ".drizzle-validators", "tmp"),
});

test("P2-10: stale table file (with generated header) is removed after regeneration", async () => {
	const root = tmpRoot("stale");
	try {
		const outDir = join(root, "gen");
		mkdirSync(outDir, { recursive: true });
		const staleFile = join(outDir, "posts.ts");
		writeFileSync(
			staleFile,
			"// AUTO-GENERATED by drizzle-validators. Do not edit.\nexport const DELETED = true;\n",
		);
		await writeGeneratedFiles({
			paths: paths(root, "gen"),
			options: { schemaPath: "./schema.ts", outputPath: "./gen" },
			viteRoot: root,
			splitByTable: true,
			moduleId: "virtual:drizzle-validators",
			data,
		});
		expect(!existsSync(staleFile)).toBe(true);
		expect(existsSync(join(outDir, "users.ts"))).toBe(true);
		expect(existsSync(join(outDir, "index.ts"))).toBe(true);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});

test("P2-10: manually-authored files (no generated header) are never touched", async () => {
	const root = tmpRoot("handmade");
	try {
		const outDir = join(root, "gen");
		mkdirSync(outDir, { recursive: true });
		const helper = join(outDir, "my-helpers.ts");
		writeFileSync(helper, "export const notGenerated = true;\n");
		const staleGenerated = join(outDir, "posts.ts");
		writeFileSync(
			staleGenerated,
			"// AUTO-GENERATED by drizzle-validators. Do not edit.\n",
		);
		await writeGeneratedFiles({
			paths: paths(root, "gen"),
			options: { schemaPath: "./schema.ts", outputPath: "./gen" },
			viteRoot: root,
			splitByTable: true,
			moduleId: "virtual:drizzle-validators",
			data,
		});
		// handmade file survives, stale generated file removed
		expect(existsSync(helper)).toBe(true);
		expect(!existsSync(staleGenerated)).toBe(true);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});

test("P2-17: outputPath inside node_modules/.drizzle-validators no longer races itself (writes survive)", async () => {
	const root = tmpRoot("inner-in");
	try {
		const outPath = "node_modules/.drizzle-validators/inner";
		// pre-existing leftovers (what generation previously rm'd mid-write)
		const pre = join(root, outPath);
		mkdirSync(pre, { recursive: true });
		await writeFile(join(pre, "users.ts"), "stale");
		await expect(
			writeGeneratedFiles({
				paths: paths(root, outPath),
				options: { schemaPath: "./schema.ts", outputPath: outPath },
				viteRoot: root,
				splitByTable: true,
				moduleId: "virtual:drizzle-validators",
				data,
			}),
		).resolves.toBeUndefined();
		const written = await readFile(join(pre, "users.ts"), "utf8");
		expect(written).toContain("export const insertSchema");
		expect(existsSync(join(pre, "index.ts"))).toBe(true);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});

test("P2-17 regression: outputs outside the internal dir still clear the old internal dir", async () => {
	const root = tmpRoot("inner");
	try {
		const oldInternal = join(root, "node_modules", ".drizzle-validators");
		mkdirSync(oldInternal, { recursive: true });
		writeFileSync(join(oldInternal, "stale.ts"), "x");
		await writeGeneratedFiles({
			paths: paths(root, "gen2"),
			options: { schemaPath: "./schema.ts", outputPath: "./gen2" },
			viteRoot: root,
			splitByTable: true,
			moduleId: "virtual:drizzle-validators",
			data,
		});
		expect(existsSync(join(oldInternal, "stale.ts"))).toBe(false);
		expect(existsSync(join(root, "gen2", "index.ts"))).toBe(true);
	} finally {
		rmSync(root, { recursive: true, force: true });
	}
});
