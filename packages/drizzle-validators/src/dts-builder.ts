import { dirname, join as joinPath, relative } from "node:path";
import type { ValidatorTarget } from "./adapters/types";
import type { GeneratedData } from "./types";

export function buildDts(opts: {
	dtsLocation: string;
	outputPath: string;
	outputDir: string;
	moduleId: string;
	target: ValidatorTarget;
	splitByTable: boolean;
	refineDtsStatement?: string;
	data: Pick<GeneratedData, "exportNames" | "tableCodes">;
}): string {
	const { dtsLocation, outputPath, outputDir, moduleId, target, splitByTable, refineDtsStatement, data } =
		opts;
	void target;
	// The refine line (refineZSchema/refineVSchema) is adapter-driven;
	// targets without a refine engine emit none.
	const refineLines = refineDtsStatement ? [refineDtsStatement] : [];

	let relImport = relative(dirname(dtsLocation), outputPath)
		.replace(/\\/g, "/")
		.replace(/\.ts$/, "");
	if (!relImport.startsWith(".")) relImport = `./${relImport}`;

	const rootExportLines = [
		...refineLines,
		...data.exportNames.map(
			(name) =>
				`export const ${name}: (typeof import('${relImport}'))['${name}']`,
		),
	].join("\n  ");

	const subModuleDeclarations: string[] = [];
	for (const tableName of data.tableCodes.keys()) {
		const insertName = `${tableName}InsertSchema`;
		const selectName = `${tableName}SelectSchema`;
		const updateName = `${tableName}UpdateSchema`;

		const subRelImport = splitByTable
			? (() => {
					let p = relative(
						dirname(dtsLocation),
						joinPath(outputDir, `${tableName}.ts`),
					)
						.replace(/\\/g, "/")
						.replace(/\.ts$/, "");
					if (!p.startsWith(".")) p = `./${p}`;
					return p;
				})()
			: relImport;

		const aliasLines = [
			...refineLines,
			`export const insertSchema: (typeof import('${subRelImport}'))['${splitByTable ? "insertSchema" : insertName}']`,
			`export const selectSchema: (typeof import('${subRelImport}'))['${splitByTable ? "selectSchema" : selectName}']`,
			`export const updateSchema: (typeof import('${subRelImport}'))['${splitByTable ? "updateSchema" : updateName}']`,
		].join("\n  ");

		subModuleDeclarations.push(
			`declare module '${moduleId}/${tableName}' {\n  ${aliasLines}\n}`,
		);
	}

	return (
		`// AUTO-GENERATED by drizzle-validators. Do not edit.\n` +
		`// Gives '${moduleId}' real, fully-inferred TypeScript types via the\n` +
		`// "(typeof import('...'))['x']" type-query form.\n` +
		`declare module '${moduleId}' {\n` +
		`  ${rootExportLines}\n` +
		`}\n\n` +
		subModuleDeclarations.join("\n\n") +
		"\n"
	);
}
