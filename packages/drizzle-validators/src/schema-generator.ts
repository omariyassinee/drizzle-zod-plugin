import { join as joinPath, resolve as resolvePath } from "node:path";
import { randomUUID } from "node:crypto";
import { DrizzleValidatorsError } from "./errors";
import { mkdir, rmdir, rm, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

import { defaultModuleId, loadAdapter } from "./adapters";
import type { ValidatorTarget } from "./adapters/types";
import { loadEsbuild } from "./esbuild-loader";

import type { GeneratedData, TableCodeData } from "./types";

export { loadEsbuild };

export async function generateSchemas(opts: {
	absoluteSchemaPath: string;
	schemaPath: string;
	tmpDir: string;
	viteRoot: string;
	tables?: string[];
	moduleId?: string;
	target?: ValidatorTarget;
	serializer?: { bufferAs: "throw" | "keep" };
}): Promise<GeneratedData> {
	const { absoluteSchemaPath, schemaPath, tmpDir, viteRoot, tables } = opts;
	const adapter = await loadAdapter(opts.target ?? "zod");
	const moduleId = opts.moduleId ?? defaultModuleId();
	const emitCtx = {
		bufferAs: opts.serializer?.bufferAs ?? "throw",
		depth: 0,
	} as const;

	// Loading the table-creators through a guarded wrapper so a missing
	// drizzle-orm (or the target's optional peer library) surfaces with an
	// actionable message (finding P2-11).
	let creators;
	try {
		creators = await adapter.loadCreators();
	} catch {
		throw new DrizzleValidatorsError(
			`Couldn't load the schema creators for target "${adapter.target}" ` +
				`(drizzle-orm/${adapter.target === "zod" ? "zod" : adapter.target}` +
				`${adapter.target === "zod" ? " or drizzle-zod" : ""}) from this environment. ` +
				`Install drizzle-orm >= 0.43 (and for non-zod targets the target library itself, e.g. ` +
				`valibot or @sinclair/typebox) in the project you are invoking this plugin/CLI from, ` +
				`then re-run generation.`,
		);
	}
	const { createInsertSchema, createSelectSchema, createUpdateSchema } =
		creators;

	const { is, Table } = await import("drizzle-orm");

	const esbuild = await loadEsbuild();

	let result;
	try {
		result = await esbuild.build({
			entryPoints: [absoluteSchemaPath],
			absWorkingDir: viteRoot,
			bundle: true,
			platform: "node",
			format: "esm",
			packages: "external",
			write: false,
			metafile: true,
			logLevel: "silent",
		});
	} catch (e) {
		// esbuild failures (missing entry file, syntax errors, unresolved
		// imports) are user-facing: rethrow with the build log attached.
		const detail =
			e && typeof e === "object" && "errors" in e
				? (e as { errors: Array<{ text?: string }> })
						.errors?.map((x) => x.text)
						.filter(Boolean)
						.join("; ")
				: undefined;
		throw new DrizzleValidatorsError(
			`Failed to bundle the schema file (${schemaPath}).` +
				(detail ? ` esbuild: ${detail}` : ""),
			{ cause: e },
		);
	}

	const bundledCode = result.outputFiles?.[0]?.text;
	if (!bundledCode) {
		throw new DrizzleValidatorsError("Failed to bundle schema file");
	}

	await mkdir(tmpDir, { recursive: true });
	// Unique per write: two plugin instances bundling in the same
	// millisecond share this dir, and a name collision would silently
	// overwrite one bundle with the other before its import.
	const tmpFile = joinPath(
		tmpDir,
		`schema-${Date.now()}-${randomUUID().slice(0, 8)}.mjs`,
	);
	await writeFile(tmpFile, bundledCode);

	let schemaModule: Record<string, unknown>;
	try {
		schemaModule = await import(pathToFileURL(tmpFile).href);
	} finally {
		// Remove the file, then the folder — non-recursively, so it is only
		// removed when EMPTY: concurrent generations (multi-instance
		// configs) stage bundles into the same dir and must not have their
		// in-flight files deleted from under them.
		await rm(tmpFile, { force: true });
		await rmdir(tmpDir).catch(() => {});
	}

	const barrelChunks: string[] = [
		"// AUTO-GENERATED by drizzle-validators. Do not edit.",
		...(adapter.refineExportStatement ? [adapter.refineExportStatement] : []),
		"",
	];

	const singleFileChunks: string[] = [
		"// AUTO-GENERATED by drizzle-validators. Do not edit.",
		adapter.importStatement,
		...(adapter.refineExportStatement ? [adapter.refineExportStatement] : []),
		"",
	];

	const tableNames =
		tables ??
		Object.entries(schemaModule)
			.filter(([, value]) => is(value, Table))
			.map(([key]) => key);

	if (tableNames.length === 0) {
		throw new DrizzleValidatorsError(
			`No Drizzle tables found in ${absoluteSchemaPath}. ` +
				`Either export some pgTable(...) values from it, or pass an explicit "tables" option.`,
		);
	}

	const exportNames: string[] = [];
	const tableCodes = new Map<string, TableCodeData>();

	// A table name that is not a valid JS identifier (e.g. "user-profile" or
	// "order items") would produce syntactically invalid export names like
	// `user-profileInsertSchema` — a syntax error in the generated file.
	// Fail loud at generation time instead (finding M3).
	const VALID_IDENTIFIER_REGEX = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/;

	for (const tableName of tableNames) {
		if (!VALID_IDENTIFIER_REGEX.test(tableName)) {
			throw new DrizzleValidatorsError(
				`Table name "${tableName}" is not a valid JS identifier — ` +
					`it cannot be used to generate export names (e.g. ${tableName}InsertSchema). ` +
					`Rename the export in your schema file, or pass an explicit "tables" list.`,
			);
		}

		const table = schemaModule[tableName] as any;
		if (!table) {
			throw new DrizzleValidatorsError(
				`Table "${tableName}" not exported from ${schemaPath}`,
			);
		}

		const insertSchema = createInsertSchema(table);
		const selectSchema = createSelectSchema(table);
		const updateSchema = createUpdateSchema(table);

		const names = [
			`${tableName}InsertSchema`,
			`${tableName}SelectSchema`,
			`${tableName}UpdateSchema`,
		];
		exportNames.push(...names);

		const insertCode = adapter.emit(insertSchema, emitCtx);
		const selectCode = adapter.emit(selectSchema, emitCtx);
		const updateCode = adapter.emit(updateSchema, emitCtx);

		barrelChunks.push(
			`export { insertSchema as ${names[0]}, selectSchema as ${names[1]}, updateSchema as ${names[2]} } from '${moduleId}/${tableName}'`,
		);

		singleFileChunks.push(
			`export const ${names[0]} = /* @__PURE__ */ ${insertCode}`,
		);
		singleFileChunks.push(
			`export const ${names[1]} = /* @__PURE__ */ ${selectCode}`,
		);
		singleFileChunks.push(
			`export const ${names[2]} = /* @__PURE__ */ ${updateCode}`,
		);
		singleFileChunks.push("");

		const subModuleChunks = [
			"// AUTO-GENERATED by drizzle-validators. Do not edit.",
			adapter.importStatement,
			...(adapter.refineExportStatement
				? [adapter.refineExportStatement]
				: []),
			"",
			`export const insertSchema = /* @__PURE__ */ ${insertCode}`,
			`export const selectSchema = /* @__PURE__ */ ${selectCode}`,
			`export const updateSchema = /* @__PURE__ */ ${updateCode}`,
		];

		tableCodes.set(tableName, {
			code: subModuleChunks.join("\n"),
			exportNames: names,
			codes: [insertCode, selectCode, updateCode],
		});
	}

	// Project-local dependency files that participated in this generation.
	// The static esbuild graph (metafile.inputs) only sees statically
	// import-ed modules; DYNAMIC imports (await import("./x.ts")) appear
	// only as per-input import records, so they must be merged in too or
	// the content hash ignores them and a change to a dynamically-imported
	// file is served stale from the disk cache (finding P2-14).
	const depPathSet = new Set<string>();
	for (const [p, input] of Object.entries(result.metafile?.inputs ?? {})) {
		if (!p.includes("node_modules")) {
			depPathSet.add(resolvePath(viteRoot, p));
		}
		for (const imp of (input as any).imports ?? []) {
			if (!imp?.dynamic || imp?.external) continue;
			if (typeof imp.path !== "string" || imp.path.includes("node_modules"))
				continue;
			depPathSet.add(resolvePath(viteRoot, imp.path));
		}
	}
	const depPaths = [...depPathSet];

	return {
		code: barrelChunks.join("\n"),
		singleFileCode: singleFileChunks.join("\n"),
		exportNames,
		tableCodes,
		depPaths,
		target: adapter.target,
		importStatement: adapter.importStatement,
		refineExportStatement: adapter.refineExportStatement,
		refineDtsStatement: adapter.refineDtsStatement,
	};
}
